"""Actual optional FELUPE + SciPy + owner/JobManager acceptance, not a formula stub.

Run with the repository's material extra (felupe==11.1.3). Synthetic observations
are generated by the actual installed adapter. The declared negative-mu portion
of the search bounds produces real adapter rejection candidates.
"""
from copy import deepcopy

import numpy as np
import pytest

pytest.importorskip('felupe', reason='Actual FELUPE material runtime required; no analytic replacement')

from caelab.evaluation import evaluate, file_hash
from caelab.evaluation_definition import document_reference
from caelab.material_document import MaterialDocuments
from caelab.numerical_document import from_material_document, request_draft
from caelab.numerical_candidate_detail import plain, table_rows, compare_candidate_details
from caelab.storage import canonical_hash
from _numerical_candidate_detail_support import DetailHost, intermediate


def histories():
    time = [0., .1, .35, 1.]
    settings = []
    for name in ('tension', 'shear', 'biaxial'):
        gradients = []
        for t in time:
            f = np.eye(3)
            if name == 'shear':
                f[0, 1] = .15*t
            else:
                f[0, 0] += .1*t
                if name == 'biaxial':
                    f[1, 1] += .07*t
            gradients.append(f.tolist())
        settings.append(dict(model='neo_hooke', parameters={'mu':1.,'lmbda':3.},
            stress_unit='MPa',time_unit='s',time=time,deformation_gradient=gradients))
    return settings


def material_command(owner, identifier, operation, arguments):
    doc = owner.read(identifier)
    return owner.command(identifier,operation,arguments,session_id=doc['session_id'],
                         expected_generation=doc['generation'])['document']


def test_actual_felupe_intermediate_success_failure_holdout_and_cold_owner(tmp_path):
    workspace = tmp_path/'한글 후보 보존'
    with DetailHost(workspace,evaluator='material.felupe') as host:
        protocols = histories()
        materials = MaterialDocuments(workspace,host.owner.session_id,host._submit,host.manager)
        material = materials.open(title='FELUPE 원 재료',draft={'backend':'material.felupe','settings':protocols[0]})
        material = material_command(materials,material['id'],'document.save',{})
        material_ref = document_reference(material)
        material_original_hash = canonical_hash(material['draft'])
        saved_material_files = {str(p.relative_to(workspace)):file_hash(p)
            for p in (workspace/'documents'/material['id']/'revisions').rglob('*') if p.is_file()}
        bound = from_material_document(material)
        bound.update(method='differential_evolution',budget=128,seed=7)
        for variable in bound['variables']:
            if variable['id']=='mu':
                variable.update(lower=-2.,upper=3.,value=1.,free=True)
            else:
                variable.update(free=False)
        data_docs, data_results = {}, {}
        for index,(name,protocol) in enumerate(zip(('tension','shear','biaxial'),protocols)):
            response = 'stress_xy' if name=='shear' else 'stress_xx'
            actual = plain(evaluate('material.felupe',protocol,values={'mu':1.25}))
            assert actual['execution_status']=='SUCCEEDED'
            assert actual['diagnostics']['library']=='felupe'
            observation = deepcopy(actual['responses'][response])
            observation.update(source_rows=[index*100+i for i in (2,5,9,12)],
                               source_column_identity=3,mask=[True,False,True,True])
            identifier,job = f'Tobs{index}',f'Jobs{index}'
            input_hash = canonical_hash({'protocol':protocol,'response':response})
            source = dict(document_id=identifier,job_id=job,input_revision=f'Robs{index}',
                          input_sha256=input_hash,response=response)
            data_docs[identifier] = dict(id=identifier,kind='data',runs=[dict(job_id=job,
                input_revision=source['input_revision'],input_sha256=input_hash)])
            data_results[identifier] = dict(execution_status='SUCCEEDED',responses={response:observation},
                diagnostics={'source_sha256':canonical_hash(plain(actual))})
            bound['experiments'].append(dict(id=name,role='holdout' if index==2 else 'fit',
                source=source,response=response,settings=deepcopy(protocol),weight=float(index+2),scale=2.))
        observations_hash = canonical_hash(data_results)
        host.owner.resolve_document = lambda ident: materials.read(ident) if ident.startswith('M') else deepcopy(data_docs[ident])
        host.owner.resolve_result = lambda ident,job,**kwargs: deepcopy(data_results[ident])
        host.owner.resolve_source_revision = materials._verify_revision
        # Reuse the existing Material-bound experiment/source compiler; use the
        # existing general Plan options to bound this dedicated test's DE run.
        assert host.owner.diagnostics(bound)==[]
        compiled = host.owner.job_arguments(bound)
        compiled['options'].update(max_generations=1,population_size=6,
            detail_retention={'candidate_limit':32,'byte_limit':16*1024*1024})
        draft = request_draft({'purpose':'Actual FELUPE multiple-trial retained candidate detail',
            'operation':'fit','inputs':compiled,'budget':{'evaluations':128}},source=material_ref)
        document = host.owner.open(title='원 재료 연계 실제 FELUPE fit',draft=draft)
        assert document['diagnostics']==[]
        doc = document['id']
        job = host.command(doc,'numerical.run',{})['job']['id']
        host.wait(job)
        original = host.owner.result(doc,job)
        original_hash = canonical_hash(original)
        success = intermediate(host,doc,job)
        failed = intermediate(host,doc,job,'FAILED')
        a,b = host.view(doc,job,success),host.view(doc,job,failed)
        assert len(host.manager.list())==1
        assert a['candidate']['values']['mu']>0
        assert b['candidate']['values']['mu']<=0
        assert a['missing_experiments']==b['missing_experiments']==['biaxial']
        assert all(t['execution_status']=='SUCCEEDED' for t in a['trials'][:2])
        assert all(t['execution_status']=='FAILED' for t in b['trials'][:2])
        assert all('moduli must be positive' in t['curve']['failure_reason'] for t in b['trials'][:2])
        for index,trial in enumerate(a['trials'][:2]):
            raw=trial['raw_evaluation']
            assert raw['diagnostics']['parameters']['mu']==a['candidate']['values']['mu']
            assert [r['deformation_gradient'] for r in raw['diagnostics']['constitutive_increments']]==protocols[index]['deformation_gradient']
            rows=table_rows(a,trial['experiment_id'])
            assert [r['source_row'] for r in rows]==data_results[f'Tobs{index}']['responses'][bound['experiments'][index]['response']]['source_rows']
            assert [r['deformation_gradient'] for r in rows]==protocols[index]['deformation_gradient']
            assert [r['weighted_residual'] for r in rows if r['included']]==trial['curve']['residual']
        assert all(r['right_prediction'] is None for r in compare_candidate_details(a,b,'shear')['rows'])
        # Mutate current owners and make mutable-source resolution fatal. Detail
        # still uses the original coefficient/protocol/observation capsules.
        changed=deepcopy(material['draft']);changed['settings']['parameters']['mu']=9.
        material_command(materials,material['id'],'material.update',{'draft':changed})
        changed_plan=deepcopy(document['draft']);changed_plan['request']['inputs']['experiments'][0]['scale']=99.
        host.command(doc,'numerical.update',{'draft':changed_plan})
        def forbidden(*args,**kwargs):
            pytest.fail('Historical detail consulted a mutable Material/Data source')
        host.owner.resolve_document=host.owner.resolve_result=host.owner.resolve_source_revision=forbidden
        completed={}
        for cid,expected_state in ((success,'SUCCEEDED'),(failed,'FAILED')):
            before=host.view(doc,job,cid)
            detail=host.detail(before)['job']['id']
            assert host.wait(detail)['state']==expected_state
            result=host.owner.result(doc,detail)
            assert result['timing']['model_calls']==1 and result['optimization_performed'] is False
            after=host.view(doc,job,cid,attempt_job_id=detail)
            assert after['trials'][:2]==before['trials'][:2]
            assert after['missing_experiments']==[]
            assert after['candidate']['execution_status']==before['candidate']['execution_status']
            completed[cid]=(detail,after)
        assert len(host.manager.list())==3
        assert canonical_hash(host.owner.result(doc,job))==original_hash
        assert canonical_hash(data_results)==observations_hash
        for name,digest in saved_material_files.items():
            assert file_hash(workspace/name)==digest
        assert canonical_hash(materials._verify_revision(material['id'],material_ref['saved_revision'])['draft'])==material_original_hash
        host.command(doc,'document.save',{})
    # A new actual controller and owner; no evaluator call on open/read/poll.
    with DetailHost(workspace,evaluator=lambda *args:pytest.fail('Cold reopen evaluated a model')) as reopened:
        for cid,(detail,previous) in completed.items():
            after=reopened.view(doc,job,cid,attempt_job_id=detail)
            assert after['trials']==previous['trials']
            assert table_rows(after,'biaxial')==table_rows(previous,'biaxial')
        assert len(reopened.manager.list())==3 and reopened.dispatched==[]
